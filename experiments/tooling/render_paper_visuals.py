def save_figure(fig, path):
    from matplotlib.text import Text

    fig.canvas.draw()
    renderer = fig.canvas.get_renderer()
    width, height = fig.bbox.width, fig.bbox.height
    for artist in fig.findobj(Text):
        if not artist.get_visible() or not artist.get_text().strip():
            continue
        check(
            artist.get_fontsize() >= FIGURE_FONT_PT,
            f"Figure text smaller than {FIGURE_FONT_PT} pt",
        )
        box = artist.get_window_extent(renderer)
        check(
            box.x0 >= -0.5
            and box.y0 >= -0.5
            and box.x1 <= width + 0.5
            and box.y1 <= height + 0.5,
            "Clipped figure text: " + artist.get_text(),
        )
    # Preserve exact print dimensions and deterministic PDF bytes (no timestamps).
    fig.savefig(
        path,
        metadata={
            "CreationDate": None,
            "ModDate": None,
            "Creator": "render_paper_visuals.py",
        },
    )


def feasible_prefixes(calibration):
    costs = calibration["generation_flops"]
    timings = {
        d: sum(s["host_s"] for s in samples) / len(samples)
        for d, samples in calibration["timings"].items()
    }
    return [
        [
            min(
                h
                for h in (1, 2, 3, 5)
                if resource["2"] / h <= b * resource["10"] * (1 + 1e-12)
            )
            for b in (0.25, 0.5, 1.0)
        ]
        for resource in (costs, timings)
    ]


