def render(destination):
    import matplotlib
    import numpy

    data = {
        name: json.loads((CAMPAIGN / path).read_text())
        for name, path in SOURCES.items()
    }
    validate(data)
    destination.mkdir(parents=True, exist_ok=True)
    contents = tables(data)
    for name, content in contents.items():
        (destination / name).write_text(content, encoding="utf-8")
    style()
    discovery_figure(data, destination / "discovery_allocation.pdf")
    confirmation_figure(data, destination / "confirmation_effects.pdf")
    study_design_figure(data, destination / "study_design.pdf")
    cost_decomposition_figure(data, destination / "cost_decomposition.pdf")
    success_compute_figure(data, destination / "success_compute_tradeoff.pdf")
    names = [
        *contents,
        "discovery_allocation.pdf",
        "confirmation_effects.pdf",
        "study_design.pdf",
        "cost_decomposition.pdf",
        "success_compute_tradeoff.pdf",
    ]
    manifest = {
        "purpose": "Presentation only; no refitting, resampling, or evidence mutation.",
        "script_sha256": digest(Path(__file__)),
        "input_sha256": {
            str((CAMPAIGN / path).relative_to(REPO)): digest(CAMPAIGN / path)
            for path in SOURCES.values()
        },
        "libraries": {"matplotlib": matplotlib.__version__, "numpy": numpy.__version__},
        "figure_width_inches": FIGURE_WIDTH,
        "minimum_figure_font_pt": FIGURE_FONT_PT,
        "output_sha256": {name: digest(destination / name) for name in names},
    }
    (destination / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    return [*names, "manifest.json"]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()
    if args.check:
        with tempfile.TemporaryDirectory(prefix="paper-visual-check-") as directory:
            temporary = Path(directory)
            names = render(temporary)
            stale = [
                name
                for name in names
                if not (args.output / name).is_file()
                or (args.output / name).read_bytes() != (temporary / name).read_bytes()
            ]
            check(not stale, "Stale publication assets: " + ", ".join(stale))
    else:
        names = render(args.output)
    print(
        f"PUBLICATION ASSETS: {len(names)} files {'match' if args.check else 'written'}; "
        "evidence unchanged, no inference or new statistics."
    )


if __name__ == "__main__":
    main()
