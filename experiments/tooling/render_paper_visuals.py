def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def number(value, signed=False):
    value = Decimal(str(round(value, 10))).quantize(
        Decimal("0.1"), rounding=ROUND_HALF_UP
    )
    return format(value, "+.1f" if signed else ".1f")


def pair(value):
    return f"$({value[0]},{value[1]})$"


def interval(bounds, scale=100):
    return "$[" + ",\\,".join(number(scale * v, True) for v in bounds) + "]$"


def table(columns, headings, rows, groups=(), footer=()):
    lines = [
        "% Generated by render_paper_visuals.py; edit the renderer, not this file.",
        r"\begin{tabular}{@{}" + columns + r"@{}}",
        r"\toprule",
        *headings,
        r"\midrule",
    ]
    for i, row in enumerate(rows):
        if i in groups:
            lines.append(r"\addlinespace[3pt]")
        lines.append(" & ".join(row) + r"\\")
    if footer:
        lines.append(r"\midrule")
        lines.extend(" & ".join(row) + r"\\" for row in footer)
    return "\n".join([*lines, r"\bottomrule", r"\end{tabular}", ""])


def check(condition, message):
    if not condition:
        raise ValueError(message)


def validate(data):
    discovery, confirmation, primary = (
        data[name] for name in ("discovery", "confirmation", "primary")
    )
    check(discovery["attempts"] == 480, "Discovery sample changed")
    check(confirmation["unique_attempts"] == 1120, "Confirmation sample changed")
    expected = [(1, 2), (1, 5), (1, 10), (2, 2), (2, 5), (5, 2), (5, 5)]
    check(
        [(r["h"], r["d"]) for r in confirmation["resources"]] == expected,
        "Unexpected confirmation order or coverage",
    )
    for r in discovery["cells"]:
        check(
            r["attempts"] == 40 and sum(r["per_task_successes"]) == r["successes"],
            "Discovery count mismatch",
        )
    resources = {(r["h"], r["d"]): r for r in confirmation["resources"]}
    for cell, r in resources.items():
        check(r["n"] == 160, "Unbalanced confirmation cell")
        check(
            sum(t["successes"][str(cell)] for t in confirmation["per_task"])
            == r["successes"],
            "Task counts differ from pooled counts",
        )
    comparisons = confirmation["comparisons"]
    check(len(comparisons) == 7, "Missing confirmation contrasts")
    for c in comparisons:
        expected_gap = (
            resources[tuple(c["a"])]["successes"]
            - resources[tuple(c["b"])]["successes"]
        ) / 160
        check(
            math.isclose(expected_gap, c["mean_difference"][0], abs_tol=1e-12),
            "Paired effect differs from pooled counts",
        )
        lo, hi = c["interval95"][0]
        check(lo <= c["mean_difference"][0] <= hi, "Invalid effect interval")
    check(comparisons[1]["kind"] == "original primary", "Primary label changed")
    p = primary["metrics"]["success"]
    check(
        math.isclose(p["paired_difference"], comparisons[1]["mean_difference"][0]),
        "Submitted primary effect differs",
    )
    check(
        all(
            math.isclose(a, b, abs_tol=1e-12)
            for a, b in zip(
                p["descriptive_95_interval"], comparisons[1]["interval95"][0]
            )
        ),
        "Submitted primary interval differs",
    )
    for frozen, c in zip(data["frozen"]["comparisons"], comparisons[:3]):
        check(frozen["recommendation"] == c["a"], "Frozen recommendation differs")


